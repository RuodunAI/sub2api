package pgdbtool

import (
	"fmt"
	"regexp"
	"slices"
	"strings"

	"gorm.io/gorm"
)

// table is one table of a schema as Drift compares it.
type table struct {
	columns map[string]column
	pkey    string // pg_get_constraintdef, "" for none
	objects []object
}

// column is what a column is defined as.
type column struct {
	Type      string // format_type
	NotNull   bool
	Default   string // pg_get_expr; the expression of a generated column
	Identity  string // attidentity: "", a or d
	Generated string // attgenerated: "", s or v
}

func (c column) String() string {
	s := c.Type
	if c.NotNull {
		s += " NOT NULL"
	}
	switch {
	case c.Generated != "":
		s += " GENERATED ALWAYS AS (" + c.Default + ") " + map[string]string{"s": "STORED", "v": "VIRTUAL"}[c.Generated]
	case c.Default != "":
		s += " DEFAULT " + c.Default
	}
	switch c.Identity {
	case "a":
		s += " GENERATED ALWAYS AS IDENTITY"
	case "d":
		s += " GENERATED BY DEFAULT AS IDENTITY"
	}
	return s
}

// object is an index or a constraint other than the primary key.
type object struct {
	kind string // "index" or "constraint"
	name string
	def  string // as PostgreSQL prints it
	// key is what makes two the same, without the names: a unique
	// constraint and a unique index on the same columns are.
	key string
}

// readCatalog reads the tables of schema.
func readCatalog(tx *gorm.DB, schema string) (map[string]*table, error) {
	// pg_get_constraintdef and pg_get_expr qualify only what search_path
	// does not show: with it on schema, both schemas print alike.
	if err := searchPath(tx, schema); err != nil {
		return nil, err
	}
	var cols []struct {
		Table, Column, Type, Default, Identity, Generated string
		NotNull                                           bool
	}
	err := tx.Raw(`SELECT c.relname AS table, a.attname AS column, format_type(a.atttypid, a.atttypmod) AS type,
			a.attnotnull AS not_null, COALESCE(pg_get_expr(d.adbin, d.adrelid), '') AS default,
			a.attidentity::text AS identity, a.attgenerated::text AS generated
		FROM pg_class c
		LEFT JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
		LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
		WHERE c.relnamespace = current_schema()::regnamespace AND c.relkind IN ('r', 'p')`).Scan(&cols).Error
	if err != nil {
		return nil, err
	}
	tables := map[string]*table{}
	for _, c := range cols {
		t := tables[c.Table]
		if t == nil {
			t = &table{columns: map[string]column{}}
			tables[c.Table] = t
		}
		if c.Column != "" { // a table without columns
			t.columns[c.Column] = column{Type: c.Type, NotNull: c.NotNull, Default: c.Default, Identity: c.Identity, Generated: c.Generated}
		}
	}
	// Constraints but NOT NULL (contype n, PostgreSQL 18: attnotnull) and
	// constraint triggers (others), and the indexes that back none.
	var rels []struct{ Table, Name, Type, Def, IndexDef string }
	err = tx.Raw(`SELECT t.relname AS table, c.conname AS name, c.contype::text AS type, pg_get_constraintdef(c.oid) AS def,
			CASE WHEN c.contype = 'u' THEN pg_get_indexdef(c.conindid) ELSE '' END AS index_def
		FROM pg_constraint c JOIN pg_class t ON t.oid = c.conrelid
		WHERE t.relnamespace = current_schema()::regnamespace AND c.contype NOT IN ('n', 't')
		UNION ALL
		SELECT t.relname, i.relname, 'i', pg_get_indexdef(x.indexrelid), ''
		FROM pg_index x JOIN pg_class i ON i.oid = x.indexrelid JOIN pg_class t ON t.oid = x.indrelid
		WHERE t.relnamespace = current_schema()::regnamespace
			AND NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conindid = x.indexrelid AND c.conrelid = x.indrelid)`).Scan(&rels).Error
	if err != nil {
		return nil, err
	}
	for _, r := range rels {
		// pg_get_indexdef qualifies the table whatever search_path.
		r.Def = strings.ReplaceAll(r.Def, " ON "+schema+".", " ON ")
		t := tables[r.Table]
		switch {
		case t == nil: // an index of a materialized view (readOthers)
		case r.Type == "p":
			t.pkey = r.Def
		case r.Type == "i":
			t.objects = append(t.objects, object{kind: "index", name: r.Name, def: r.Def, key: indexKey(r.Def)})
		case r.Type == "u":
			// The unique index it makes, and whether it is deferrable,
			// which no index says.
			t.objects = append(t.objects, object{kind: "constraint", name: r.Name, def: r.Def,
				key: indexKey(r.IndexDef) + deferrable.FindString(r.Def)})
		default:
			t.objects = append(t.objects, object{kind: "constraint", name: r.Name, def: r.Def, key: r.Type + " " + r.Def})
		}
	}
	return tables, nil
}

var (
	// indexName is the head of pg_get_indexdef up to the table: the names.
	indexName  = regexp.MustCompile(`^CREATE (UNIQUE )?INDEX (?:"(?:[^"]|"")+"|\S+) ON (ONLY )?(?:"(?:[^"]|"")+"|\S+) `)
	deferrable = regexp.MustCompile(` DEFERRABLE.*$`)
)

// indexKey is an index definition without its name and table's.
func indexKey(def string) string { return indexName.ReplaceAllString(def, "${1}INDEX ${2}") }

// comparer collects how the migrated schema (have) differs from the
// models' (want).
type comparer struct {
	tx          *gorm.DB
	unmapped    []string
	differences []string
}

func (c *comparer) differ(format string, args ...any) {
	c.differences = append(c.differences, fmt.Sprintf(format, args...))
}

// compare compares the tables.
func (c *comparer) compare(have, want map[string]*table) {
	for name, h := range have {
		w := want[name]
		if w == nil {
			c.unmapped = append(c.unmapped, "table "+name)
			continue
		}
		c.columns(name, h.columns, w.columns)
		if h.pkey != w.pkey {
			c.differ("primary key %s: migrations: %s; models: %s", name, orNone(h.pkey), orNone(w.pkey))
		}
		c.objects(name, h.objects, w.objects)
	}
	for name := range want {
		if have[name] == nil {
			c.differ("table %s: not in migrations", name)
		}
	}
}

// others takes what no model can describe (readOthers) for unmapped, but
// the objects the model package declares unmanaged.
func (c *comparer) others(others, unmanaged []string) {
	for _, o := range others {
		if !slices.Contains(unmanaged, o) {
			c.unmapped = append(c.unmapped, o)
		}
	}
	for _, u := range unmanaged {
		if !slices.Contains(others, u) {
			c.differ("unmanaged %s: not in migrations", u)
		}
	}
}

func orNone(s string) string {
	if s == "" {
		return "none"
	}
	return s
}

func (c *comparer) columns(table string, have, want map[string]column) {
	for name, h := range have {
		w, ok := want[name]
		switch {
		case !ok:
			c.unmapped = append(c.unmapped, "column "+table+"."+name)
		case h.Type != w.Type || h.NotNull != w.NotNull || h.Identity != w.Identity || h.Generated != w.Generated ||
			!c.sameDefault(h.Type, h.Default, w.Default):
			c.differ("column %s.%s: migrations: %s; models: %s", table, name, h, w)
		}
	}
	for name, w := range want {
		if _, ok := have[name]; !ok {
			c.differ("column %s.%s: not in migrations (models: %s)", table, name, w)
		}
	}
}

// sameDefault reports whether defaults a and b of a column of type typ give
// the same value. The models' are written by GORM, and PostgreSQL keeps 0
// and '0'::numeric, CURRENT_TIMESTAMP and now() apart as text. Both are
// evaluated, in a savepoint (an expression that cannot be is not the
// same); now() is the transaction's start in either. A sequence is never
// advanced: nextval() compares as text.
func (c *comparer) sameDefault(typ, a, b string) bool {
	switch {
	case a == b:
		return true
	case a == "" || b == "" || strings.Contains(a+b, "nextval("):
		return false
	}
	var same bool
	err := c.tx.Transaction(func(tx *gorm.DB) error {
		return tx.Raw("SELECT ((" + a + ")::" + typ + ")::text IS NOT DISTINCT FROM ((" + b + ")::" + typ + ")::text").Row().Scan(&same)
	})
	return err == nil && same
}

// objects pairs indexes and constraints of the same definition, those of
// the same name first; a pair of the same name left over is defined
// differently.
func (c *comparer) objects(table string, have, want []object) {
	want = slices.Clone(want)
	var left []object
	for _, sameName := range []bool{true, false} {
		left = nil
		for _, h := range have {
			j := slices.IndexFunc(want, func(w object) bool { return w.key == h.key && (!sameName || w.name == h.name) })
			if j < 0 {
				left = append(left, h)
				continue
			}
			want = slices.Delete(want, j, j+1)
		}
		have = left
	}
	for _, h := range left {
		if j := slices.IndexFunc(want, func(w object) bool { return w.name == h.name }); j >= 0 {
			c.differ("%s %s.%s: migrations: %s; models: %s", h.kind, table, h.name, h.def, want[j].def)
			want = slices.Delete(want, j, j+1)
			continue
		}
		if h.kind == "index" {
			c.unmapped = append(c.unmapped, "index "+table+"."+h.name)
		} else {
			c.unmapped = append(c.unmapped, "constraint "+table+"."+h.name+" "+h.def)
		}
	}
	for _, w := range want {
		c.differ("%s %s.%s: not in migrations (models: %s)", w.kind, table, w.name, w.def)
	}
}

// readOthers lists what no model can describe in schema, by the names of
// DriftReport.Unmapped. A sequence of a serial or
// identity column belongs to its column, objects of an extension to the
// extension, a multirange type to its range.
func readOthers(tx *gorm.DB, schema string) ([]string, error) {
	if err := searchPath(tx, schema); err != nil {
		return nil, err
	}
	var out []string
	err := tx.Raw(`SELECT CASE c.relkind WHEN 'S' THEN 'sequence ' WHEN 'm' THEN 'materialized view ' ELSE 'view ' END || c.relname
		FROM pg_class c
		WHERE c.relnamespace = current_schema()::regnamespace AND c.relkind IN ('S', 'v', 'm')
			AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_class'::regclass AND d.objid = c.oid AND d.deptype IN ('a', 'i', 'e'))
		UNION ALL
		SELECT 'function ' || p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')'
		FROM pg_proc p
		WHERE p.pronamespace = current_schema()::regnamespace
			AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e')
		UNION ALL
		SELECT 'trigger ' || c.relname || '.' || g.tgname
		FROM pg_trigger g JOIN pg_class c ON c.oid = g.tgrelid
		WHERE c.relnamespace = current_schema()::regnamespace AND NOT g.tgisinternal
		UNION ALL
		SELECT 'type ' || t.typname
		FROM pg_type t
		WHERE t.typnamespace = current_schema()::regnamespace AND t.typtype IN ('e', 'd', 'r', 'm')
			AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_type'::regclass AND d.objid = t.oid AND d.deptype IN ('i', 'e'))`).Scan(&out).Error
	return out, err
}
