// Package modelgen generates the GORM models in internal/store/model from
// the PostgreSQL catalog of a database migrated with the core migrations.
//
// It reads pg_catalog itself instead of using gorm.io/gen: the models must
// map numeric to decimal.Decimal (gen picks float64 and loses precision),
// arrays to store.Int64s / store.Strings and jsonb to json.RawMessage, and
// carry exact default-value tags. gen's per-type hooks can do most of that
// but drag in its query-builder dependencies for a few hundred lines of
// output we fully control here. The SQL migrations stay the only schema
// source; the models are derived from them, never the other way around.
package modelgen

import (
	"bytes"
	"context"
	"fmt"
	"go/format"
	"path"
	"sort"
	"strings"

	"github.com/jinzhu/inflection"

	"github.com/Sub2API-Devs/sup2api/next/server/internal/store"
)

// Header starts every generated file; it is how Write and ReadGenerated
// tell generated files from hand-written ones in the same directory.
const Header = "// Code generated by go run ./cmd/gen-models; DO NOT EDIT.\n"

// Config selects the tables to generate and how to name them.
type Config struct {
	Package string
	Schema  string
	// Exclude holds path.Match patterns of table names left out.
	Exclude []string
	// Names overrides the struct name derived from a table name.
	Names map[string]string
}

// Default generates the core tables of the public schema. Plugin schemas
// (plg_*) are outside it; the River queue tables belong to River and the
// migration trackers to the migrator, so no code writes them through GORM.
var Default = Config{
	Package: "model",
	Schema:  "public",
	Exclude: []string{"schema_migrations", "plugin_migrations", "river_*"},
	Names: map[string]string{
		"authz_meta": "AuthzMeta", // inflection would say "AuthzMetum"
	},
}

const storePkg = "github.com/Sub2API-Devs/sup2api/next/server/internal/store"

type goType struct {
	name string
	pkg  string // import path, "" for builtins
	// nilable types already represent NULL as nil, so a nullable column
	// does not get a pointer.
	nilable bool
	// dbType goes into the type: tag where GORM cannot infer a data type:
	// it takes an untyped slice field for a has-many relation.
	dbType string
}

// goTypes maps pg_type.typname (the base type for a domain) to the field
// type. A column of any other type fails generation, so a new type gets a
// deliberate mapping instead of a silent guess (timestamp without time zone,
// for one, needs a decision about zones).
var goTypes = map[string]goType{
	"int8":        {name: "int64"},
	"int4":        {name: "int"}, // the repo holds integer columns in int
	"int2":        {name: "int"},
	"float8":      {name: "float64"},
	"float4":      {name: "float32"},
	"bool":        {name: "bool"},
	"text":        {name: "string"},
	"varchar":     {name: "string"},
	"bpchar":      {name: "string"},
	"uuid":        {name: "string"},
	"numeric":     {name: "decimal.Decimal", pkg: "github.com/shopspring/decimal"},
	"timestamptz": {name: "time.Time", pkg: "time"},
	"bytea":       {name: "[]byte", nilable: true},
	"json":        {name: "json.RawMessage", pkg: "encoding/json", nilable: true},
	"jsonb":       {name: "json.RawMessage", pkg: "encoding/json", nilable: true},
	"_int8":       {name: "store.Int64s", pkg: storePkg, dbType: "bigint[]"},
	"_text":       {name: "store.Strings", pkg: storePkg, dbType: "text[]"},
	"_varchar":    {name: "store.Strings", pkg: storePkg, dbType: "varchar[]"},
}

type table struct {
	name    string
	comment string
	cols    []column
}

type column struct {
	name      string
	typName   string
	enum      bool
	sqlType   string
	notNull   bool
	def       string
	identity  bool
	generated bool
	pk        bool
	comment   string
}

// Generate reads the tables of cfg.Schema through q and returns the model
// files by name.
func Generate(ctx context.Context, q store.Querier, cfg Config) (map[string][]byte, error) {
	tables, err := readTables(ctx, q, cfg)
	if err != nil {
		return nil, err
	}
	files := map[string][]byte{"doc.go": docFile(cfg)}
	structs := map[string]string{}
	var unmapped []string
	for _, t := range tables {
		name := structName(cfg, t.name)
		if prev, dup := structs[name]; dup {
			return nil, fmt.Errorf("tables %s and %s both map to struct %s; add a Config.Names entry", prev, t.name, name)
		}
		structs[name] = t.name
		src, bad := render(cfg, name, t)
		unmapped = append(unmapped, bad...)
		files[t.name+".gen.go"] = src
	}
	if len(unmapped) > 0 {
		return nil, fmt.Errorf("columns without a Go type mapping (add them to goTypes): %s", strings.Join(unmapped, ", "))
	}
	for name, src := range files {
		out, err := format.Source(src)
		if err != nil {
			return nil, fmt.Errorf("format %s: %w", name, err)
		}
		files[name] = out
	}
	return files, nil
}

const catalogSQL = `
SELECT c.relname,
       coalesce(obj_description(c.oid, 'pg_class'), ''),
       a.attname,
       CASE WHEN t.typtype = 'd' THEN bt.typname ELSE t.typname END,
       t.typtype = 'e',
       format_type(a.atttypid, a.atttypmod),
       a.attnotnull,
       coalesce(pg_get_expr(d.adbin, d.adrelid), ''),
       a.attidentity <> '',
       a.attgenerated <> '',
       EXISTS (SELECT 1 FROM pg_constraint p
               WHERE p.conrelid = c.oid AND p.contype = 'p' AND a.attnum = ANY (p.conkey)),
       coalesce(col_description(c.oid, a.attnum), '')
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
JOIN pg_type t ON t.oid = a.atttypid
LEFT JOIN pg_type bt ON bt.oid = t.typbasetype
LEFT JOIN pg_attrdef d ON d.adrelid = c.oid AND d.adnum = a.attnum
WHERE n.nspname = $1 AND c.relkind IN ('r', 'p') AND NOT c.relispartition
ORDER BY c.relname, a.attnum`

func readTables(ctx context.Context, q store.Querier, cfg Config) ([]table, error) {
	rows, err := q.Query(ctx, catalogSQL, cfg.Schema)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var tables []table
	for rows.Next() {
		var tname, tcomment string
		var c column
		if err := rows.Scan(&tname, &tcomment, &c.name, &c.typName, &c.enum, &c.sqlType, &c.notNull,
			&c.def, &c.identity, &c.generated, &c.pk, &c.comment); err != nil {
			return nil, err
		}
		excluded, err := matchAny(cfg.Exclude, tname)
		if err != nil {
			return nil, err
		}
		if excluded {
			continue
		}
		if n := len(tables); n == 0 || tables[n-1].name != tname {
			tables = append(tables, table{name: tname, comment: tcomment})
		}
		t := &tables[len(tables)-1]
		t.cols = append(t.cols, c)
	}
	return tables, rows.Err()
}

func matchAny(patterns []string, name string) (bool, error) {
	for _, p := range patterns {
		ok, err := path.Match(p, name)
		if err != nil {
			return false, fmt.Errorf("exclude pattern %q: %w", p, err)
		}
		if ok {
			return true, nil
		}
	}
	return false, nil
}

func docFile(cfg Config) []byte {
	return []byte(Header + `
// Package ` + cfg.Package + ` holds the GORM models of the core tables, one
// struct per table, generated from a database migrated with the core
// migrations. The SQL migrations stay the schema source: change a table
// there, then regenerate; never AutoMigrate these models.
//
// A column with a database default (serial ids, now(), literals) is tagged
// default:(-): GORM leaves it out of an INSERT while the field holds its zero
// value and reads the database's value back with RETURNING, as an INSERT
// that omits the column would. GORM skips such a zero field even when it is
// selected, so writing an explicit zero (false into a default-true column)
// takes a map insert, Create(map[string]any{...}). Nullable columns are
// pointers, except []byte and json.RawMessage, where nil already is NULL.
package ` + cfg.Package + "\n")
}

// render returns the source of one table's file and the columns it could
// not map.
func render(cfg Config, name string, t table) ([]byte, []string) {
	var body bytes.Buffer
	imports := map[string]bool{}
	var unmapped []string

	fmt.Fprintf(&body, "// %s is a row of table %s.\n", name, t.name)
	writeComment(&body, t.comment, "")
	fmt.Fprintf(&body, "type %s struct {\n", name)
	for _, c := range t.cols {
		typ, ok := fieldType(c)
		if !ok {
			unmapped = append(unmapped, fmt.Sprintf("%s.%s (%s)", t.name, c.name, c.sqlType))
			continue
		}
		if typ.pkg != "" {
			imports[typ.pkg] = true
		}
		field := goName(c.name)
		writeComment(&body, c.comment, "\t")
		fmt.Fprintf(&body, "\t%s %s `gorm:\"%s\"` // %s\n", field, typ.name, tag(field, typ, c), describe(c))
	}
	body.WriteString("}\n\n")
	fmt.Fprintf(&body, "// TableName implements gorm's schema.Tabler.\nfunc (%s) TableName() string { return %q }\n", name, t.name)

	var src bytes.Buffer
	src.WriteString(Header + "\npackage " + cfg.Package + "\n\n")
	writeImports(&src, imports)
	src.Write(body.Bytes())
	return src.Bytes(), unmapped
}

func fieldType(c column) (goType, bool) {
	if c.enum {
		return goType{name: "string"}, true
	}
	typ, ok := goTypes[c.typName]
	if ok && !c.notNull && !typ.nilable {
		typ.name = "*" + typ.name
	}
	return typ, ok
}

// tag is the gorm struct tag of a column. GORM infers behavior from names
// and types that the database already defines; the tag turns each inference
// off or states the database's rule instead.
func tag(field string, typ goType, c column) string {
	parts := []string{"column:" + c.name}
	if typ.dbType != "" {
		parts = append(parts, "type:"+typ.dbType)
	}
	if c.pk {
		parts = append(parts, "primaryKey")
	}
	switch {
	case c.generated:
		parts = append(parts, "->") // the database computes it; never written
	case c.def != "" || c.identity:
		// A parenthesized value keeps GORM from parsing the default into a
		// Go value it would substitute for a zero field: the zero value is
		// omitted and the database's default comes back through RETURNING.
		parts = append(parts, "default:(-)")
	case c.pk && strings.HasPrefix(c.typName, "int"):
		// GORM treats a sole integer primary key as auto-increment and drops
		// it from INSERT when zero; this one has no sequence behind it.
		parts = append(parts, "autoIncrement:false")
	}
	// GORM stamps fields with these names from the Go clock on create and
	// update; the database's defaults and triggers own them.
	switch field {
	case "CreatedAt":
		parts = append(parts, "autoCreateTime:false")
	case "UpdatedAt":
		parts = append(parts, "autoUpdateTime:false")
	}
	return strings.Join(parts, ";")
}

func describe(c column) string {
	s := c.sqlType
	switch {
	case c.generated:
		s += " generated " + c.def
	case c.identity:
		s += " identity"
	case c.def != "":
		s += " default " + c.def
	}
	return strings.ReplaceAll(s, "\n", " ")
}

func writeComment(b *bytes.Buffer, text, indent string) {
	if text == "" {
		return
	}
	for _, line := range strings.Split(strings.TrimSpace(text), "\n") {
		fmt.Fprintf(b, "%s// %s\n", indent, strings.TrimRight(line, " \t\r"))
	}
}

func writeImports(b *bytes.Buffer, imports map[string]bool) {
	if len(imports) == 0 {
		return
	}
	var std, other []string
	for p := range imports {
		if strings.Contains(strings.SplitN(p, "/", 2)[0], ".") {
			other = append(other, p)
		} else {
			std = append(std, p)
		}
	}
	sort.Strings(std)
	sort.Strings(other)
	b.WriteString("import (\n")
	for _, p := range std {
		fmt.Fprintf(b, "\t%q\n", p)
	}
	if len(std) > 0 && len(other) > 0 {
		b.WriteString("\n")
	}
	for _, p := range other {
		fmt.Fprintf(b, "\t%q\n", p)
	}
	b.WriteString(")\n\n")
}

func structName(cfg Config, tableName string) string {
	if n, ok := cfg.Names[tableName]; ok {
		return n
	}
	return goName(inflection.Singular(tableName))
}

// initialisms are written upper-case in Go names, as golint expects.
var initialisms = map[string]bool{
	"api": true, "cpu": true, "dns": true, "html": true, "http": true, "https": true,
	"id": true, "ip": true, "json": true, "jwt": true, "rpc": true,
	"sql": true, "ssh": true, "tcp": true, "tls": true, "totp": true, "ttl": true,
	"ui": true, "uid": true, "uri": true, "url": true, "uuid": true, "xml": true,
}

// goName turns a snake_case identifier into an exported Go name.
func goName(snake string) string {
	var b strings.Builder
	for _, w := range strings.Split(snake, "_") {
		if w == "" {
			continue
		}
		switch {
		case w == "ids":
			b.WriteString("IDs")
		case w == "ips":
			b.WriteString("IPs")
		case initialisms[w]:
			b.WriteString(strings.ToUpper(w))
		default:
			b.WriteString(strings.ToUpper(w[:1]) + w[1:])
		}
	}
	return b.String()
}
